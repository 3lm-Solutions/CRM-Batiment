import {
  CallHandler,
  ExecutionContext,
  HttpStatus,
  Injectable,
  NestInterceptor,
  StreamableFile,
} from '@nestjs/common';
import type { Response } from 'express';
import { catchError, from, mergeMap, Observable, of, throwError } from 'rxjs';
import { Prisma } from '../../generated/prisma/client';
import { PrismaService } from '../../prisma/prisma.service';
import type { AppRequest } from '../auth/auth-user.interface';
import { BusinessException } from '../exceptions/business.exception';

/** Methods that change something: a GET is already safe to repeat. */
const METHODES = new Set(['POST', 'PUT', 'PATCH', 'DELETE']);
/** A UUID or any similar random string generated by the phone */
export const FORMAT_CLE = /^[A-Za-z0-9_.:-]{8,100}$/;
/** A key is remembered 24 h (long enough for a phone that stayed offline all day) */
const DUREE_MS = 24 * 3600_000;
/** A request still « in progress » after this long was interrupted (server restart…) */
const ABANDON_MS = 2 * 60_000;
/** Bigger answers are not kept (they are never needed for a replay in practice) */
const TAILLE_MAX = 512 * 1024;

type Cle = {
  id: number;
  methode: string;
  chemin: string;
  statut: string;
  codeHttp: number | null;
  reponse: Prisma.JsonValue | null;
  createdAt: Date;
};

/**
 * 16/11 (mobile lot 1) — sending again without doing twice.
 *
 * The phone keeps the actions made without network and sends them again later. It adds a
 * header « Idempotency-Key: <random id> » (the same id at each attempt). The first time the
 * action is done and its answer kept; the next times the SAME answer is returned and nothing
 * is done again (no second SAV ticket, no second photo…).
 *
 *  - without the header nothing changes (the web never sends it);
 *  - the key belongs to one user; reused on another address → 422 CLE_IDEMPOTENCE_REUTILISEE;
 *  - same key while the first request still runs → 409 REQUETE_EN_COURS (retry later);
 *  - a request that fails is forgotten: it can be sent again with the same key.
 */
@Injectable()
export class IdempotencyInterceptor implements NestInterceptor {
  constructor(private readonly prisma: PrismaService) {}

  async intercept(ctx: ExecutionContext, next: CallHandler): Promise<Observable<unknown>> {
    if (ctx.getType() !== 'http') return next.handle();
    const req = ctx.switchToHttp().getRequest<AppRequest>();
    const res = ctx.switchToHttp().getResponse<Response>();
    const cle = req.headers['idempotency-key'];
    if (cle === undefined || !METHODES.has(req.method) || !req.user) return next.handle();
    if (typeof cle !== 'string' || !FORMAT_CLE.test(cle)) {
      throw new BusinessException(
        'CLE_IDEMPOTENCE_INVALIDE',
        'En-tête Idempotency-Key invalide (8 à 100 caractères : lettres, chiffres, - _ . :).',
        HttpStatus.BAD_REQUEST,
      );
    }
    const userId = req.user.id;
    const methode = req.method;
    const chemin = req.originalUrl.split('?')[0];

    const existante = await this.lire(userId, cle);
    if (existante) {
      const rejeu = this.rejouer(existante, methode, chemin, res);
      if (rejeu) return rejeu;
    }

    let id: number;
    try {
      // Housekeeping: this user's expired keys
      await this.prisma.cleIdempotence.deleteMany({
        where: { userId, createdAt: { lt: new Date(Date.now() - DUREE_MS) } },
      });
      ({ id } = await this.prisma.cleIdempotence.create({
        data: { userId, cle, methode, chemin },
        select: { id: true },
      }));
    } catch (error) {
      // Two sends at the same moment: the other one created the key first
      if (error instanceof Prisma.PrismaClientKnownRequestError && error.code === 'P2002') {
        throw new BusinessException(
          'REQUETE_EN_COURS',
          'Cette action est déjà en cours d’envoi. Réessayez dans un instant.',
          HttpStatus.CONFLICT,
        );
      }
      throw error;
    }

    return next.handle().pipe(
      mergeMap((body) =>
        from(this.memoriser(id, res.statusCode, body)).pipe(mergeMap(() => of(body))),
      ),
      catchError((error: unknown) =>
        from(this.oublier(id)).pipe(mergeMap(() => throwError(() => error))),
      ),
    );
  }

  private lire(userId: number, cle: string): Promise<Cle | null> {
    return this.prisma.cleIdempotence.findUnique({
      where: { userId_cle: { userId, cle } },
      select: {
        id: true,
        methode: true,
        chemin: true,
        statut: true,
        codeHttp: true,
        reponse: true,
        createdAt: true,
      },
    });
  }

  /** Returns the kept answer, or null when the key is stale and the action must run again. */
  private rejouer(cle: Cle, methode: string, chemin: string, res: Response) {
    const age = Date.now() - cle.createdAt.getTime();
    if (age > DUREE_MS || (cle.statut === 'EN_COURS' && age > ABANDON_MS)) {
      void this.oublier(cle.id);
      return null;
    }
    if (cle.methode !== methode || cle.chemin !== chemin) {
      throw new BusinessException(
        'CLE_IDEMPOTENCE_REUTILISEE',
        'Cette clé a déjà servi pour une autre action. Générez une nouvelle clé.',
      );
    }
    if (cle.statut === 'EN_COURS') {
      throw new BusinessException(
        'REQUETE_EN_COURS',
        'Cette action est déjà en cours d’envoi. Réessayez dans un instant.',
        HttpStatus.CONFLICT,
      );
    }
    res.status(cle.codeHttp ?? HttpStatus.OK);
    res.setHeader('Idempotent-Replayed', 'true');
    return of(cle.reponse ?? undefined);
  }

  private async memoriser(id: number, codeHttp: number, body: unknown): Promise<void> {
    // A file (PDF…) is not kept: asking for it again is harmless
    if (body instanceof StreamableFile || Buffer.isBuffer(body)) return this.oublier(id);
    const json = body === undefined ? undefined : JSON.stringify(body);
    if (json && json.length > TAILLE_MAX) return this.oublier(id);
    await this.prisma.cleIdempotence
      .update({
        where: { id },
        data: {
          statut: 'TERMINE',
          codeHttp,
          reponse: json === undefined ? Prisma.DbNull : (JSON.parse(json) as Prisma.InputJsonValue),
        },
      })
      .catch(() => undefined);
  }

  private async oublier(id: number): Promise<void> {
    await this.prisma.cleIdempotence.deleteMany({ where: { id } }).catch(() => undefined);
  }
}
